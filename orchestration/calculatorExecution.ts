export type CalculatorExecutionTeam = {
  /** Host-owned failure capability; carries complete feedback separately from bounded issue labels. */
  prepareRepairFeedback?(plan: CalculatorPlan, id: string, previous: PreparedCalculatorChanges,
    tests?: CalculatorProposalTests): CalculatorRepairRequest;
  generate(plan: CalculatorPlan, id: string, snapshot: CalculatorSnapshot): Promise<PreparedCalculatorChanges>;
  repair(plan: CalculatorPlan, id: string, snapshot: CalculatorSnapshot, request: CalculatorRepairRequest): Promise<PreparedCalculatorChanges>;
  assess(role: "security" | "reviewer" | "tester", plan: CalculatorPlan, id: string, changes: PreparedCalculatorChanges): Promise<CalculatorAssessment>;
};
/** These callbacks are trusted host tools, never generated by a model. No default
 * success exists. The live adapters and isolation must be configured separately. */
export type CalculatorExecutionTools = {
  checkProposal(input: { task: CalculatorPlanTask; changes: PreparedCalculatorChanges; proposalDigest: string }): Promise<CalculatorProposalTests>;
  publish(input: { task: CalculatorPlanTask; changes: PreparedCalculatorChanges; expectedSha: string; branch: string }): Promise<TeamTaskPublication>;
  ci(input: { repository: string; branch: string; candidateSha: string }): Promise<{
    repository: string; branch: string; candidateSha: string; runs: WorkflowRun[]; jobs: CiJob[];
  }>;
};
export type CalculatorExecutionReport = Readonly<{
  status: "blocked" | "needs-review" | "candidate-verified"; reasonCode: string; taskId?: string;
  attempts: number; repairs: number; publication?: Readonly<TeamTaskPublication>;
  proposalTestsExecuted: boolean; candidateTestsExecuted: boolean;
  publicationDiagnostic?: CalculatorPublicationDiagnostic;
  wholeAppCompleted: false; finalCalculatorCiVerified: false; legalEnabled: false;
}>;
/** Private host evidence, persisted before advancing. This is data, never replay
 * authorization; source-free task receipts remain separate. */
export type CalculatorExecutionCheckpointEvent = Readonly<{
  taskId: string; attempt: 1 | 2; stage: string; status: "running" | "passed" | "blocked";
  proposal?: PreparedCalculatorChanges; assessments: readonly CalculatorAssessment[];
  publicationStarted: boolean;
}>;
/** One claimed task, at most one repair, no whole-task replay or idle CI polling.
 * Task CI is explicitly separate from the unchanged final Calculator CI gate. */
export async function runCalculatorExecution(workspace: CalculatorWorkspace, options: {
  team: CalculatorExecutionTeam; tools: CalculatorExecutionTools; verifyDependencies?: CalculatorCheckRunner;
  checkpoint?: (event: CalculatorExecutionCheckpointEvent) => void | Promise<void>;
  /** Trusted host may remove the single repair allowance, never increase it. */
  maxRepairs?: 0 | 1;
  /** Verified, explicit host continuation only; rebuilding calls no developer. */
  restoreProposal?: (plan: CalculatorPlan, id: string, snapshot: CalculatorSnapshot) => PreparedCalculatorChanges | Promise<PreparedCalculatorChanges>;
  /** Only canonical assessments revalidated by the host team are eligible. */
  restoreAssessments?: (plan: CalculatorPlan, id: string, changes: PreparedCalculatorChanges) => readonly CalculatorAssessment[] | Promise<readonly CalculatorAssessment[]>;
  queuedSuccessorPermit?: CalculatorQueuedPermit;
  historicalT03Permit?: CalculatorT02ExecutionPermit;
  repairContinuationPermit?: CalculatorT03RepairPermit;
  rejectedProposalPermit?:CalculatorRuntimeRecoveryPermit;
  env?: NodeJS.ProcessEnv; execution?: "live" | "offline-test";
}): Promise<CalculatorExecutionReport> {
  let receipt: TeamTaskStore | undefined, publication: TeamTaskPublication | undefined, task: CalculatorPlanTask | undefined;
  let publicationDiagnostic:CalculatorPublicationDiagnostic|undefined;
  let attempts = 0, repairs = 0, proposalTestsExecuted = false, candidateTestsExecuted = false;
  let activeStage: string | undefined, publicationStarted = false;
  let activeAttempt: 1 | 2 = 1, checkpointProposal: PreparedCalculatorChanges | undefined;
  let assessments: CalculatorAssessment[] = [];
  const answer = (status: CalculatorExecutionReport["status"], reasonCode: string): CalculatorExecutionReport => Object.freeze({
    status, reasonCode, ...(task ? { taskId: task.id } : {}), attempts, repairs,
    ...(publication ? { publication: Object.freeze({ ...publication }) } : {}), ...(publicationDiagnostic?{publicationDiagnostic}:{}),proposalTestsExecuted, candidateTestsExecuted,
    wholeAppCompleted: false, finalCalculatorCiVerified: false, legalEnabled: false,
  });
  async function checkpoint(stageName: string, status: CalculatorExecutionCheckpointEvent["status"]) {
    if (task && options.checkpoint) await options.checkpoint(Object.freeze({ taskId: task.id, attempt: activeAttempt,
      stage: stageName, status, ...(checkpointProposal ? { proposal: checkpointProposal } : {}),
      assessments: Object.freeze([...assessments]), publicationStarted }));
  }
  async function finish(status: "blocked" | "needs-review", reason: string,
    reportStatus: CalculatorExecutionReport["status"] = status, save = true) {
    if (save) await checkpoint("execution_complete", status === "blocked" ? "blocked" : "passed");
    receipt?.finish(status, reason); return answer(reportStatus, reason);
  }
  async function stage<T>(name: string, action: () => Promise<T>): Promise<T> {
    activeStage = name; receipt!.recordStage(name, "running");
    await checkpoint(name, "running");
    const value = await action();
    await checkpoint(name, "passed");
    receipt!.recordStage(name, "passed"); activeStage = undefined; return value;
  }
  try {
    // Configuration failures do not consume a task identity or invoke a model.
    if (options.maxRepairs !== undefined && options.maxRepairs !== 0 && options.maxRepairs !== 1) return refuseCalculatorExecution();
    if (options.restoreProposal !== undefined && (typeof options.restoreProposal !== "function" || options.maxRepairs !== 0)) return refuseCalculatorExecution();
    if (options.restoreAssessments !== undefined && (typeof options.restoreAssessments !== "function" ||
        typeof options.restoreProposal !== "function" || options.maxRepairs !== 0)) return refuseCalculatorExecution();
    if (options.repairContinuationPermit && (options.maxRepairs !== 0 || options.historicalT03Permit || options.restoreProposal || options.restoreAssessments)) return refuseCalculatorExecution();
    if(options.queuedSuccessorPermit&&(options.repairContinuationPermit||options.historicalT03Permit||options.restoreProposal||options.restoreAssessments))return refuseCalculatorExecution();
    if(options.rejectedProposalPermit&&(options.maxRepairs!==0||options.queuedSuccessorPermit||options.repairContinuationPermit||options.historicalT03Permit||options.restoreProposal||options.restoreAssessments))return refuseCalculatorExecution();
    const maxRepairs = options.maxRepairs ?? 1;
    const env = options.env ?? process.env;
    if ((options.execution ?? "live") === "live" && (env.CALCULATOR_EXECUTION_LIVE_APPROVED !== "RUN_ONE_FREE_CALCULATOR_TASK" ||
        env.AGENT_FACTORY_ENABLE_GITHUB_WRITES !== "true" || env.AGENT_FACTORY_LEGAL_ENABLED !== "false" ||
        env.AGENT_FACTORY_TARGET_PROFILE !== "calculator" || env.ONAY_TEAM_FREE_TIER_CONFIRMED !== "true" ||
        env.AGENT_FACTORY_ALLOW_WORKFLOW_CHANGES === "true" ||
        !env.AGENT_ALLOWED_REPOSITORIES?.split(",").map(value => value.trim()).includes(CALCULATOR_PROFILE.repository))) return refuseCalculatorExecution();
    if (!options.team || !options.tools || [options.tools.checkProposal, options.tools.publish, options.tools.ci,
        options.team.generate, options.team.repair, options.team.assess].some(value => typeof value !== "function")) return refuseCalculatorExecution();
    const plan = await calculatorWorkspacePlan(workspace);
    const claimed = options.rejectedProposalPermit ? await claimCalculatorRuntimeRecovery(workspace,options.rejectedProposalPermit) : options.queuedSuccessorPermit ? await claimCalculatorQueuedSuccessor(workspace,options.queuedSuccessorPermit) : options.repairContinuationPermit ?
      await claimCalculatorT03RepairContinuation(workspace,options.repairContinuationPermit) : options.historicalT03Permit ?
      await claimHistoricalCalculatorT03(workspace,options.historicalT03Permit,options.verifyDependencies) :
      await claimCalculatorWorkspaceTask(workspace, options.verifyDependencies);
    receipt = claimed.store; task = claimed.selection.task;
    if (!receipt || !task) return answer(claimed.selection.status === "blocked" ? "blocked" : "needs-review", claimed.selection.reasonCode);
    if(options.rejectedProposalPermit){activeAttempt=2;repairs=1;}
    const snapshot = await stage("load_current_source", () => loadCalculatorWorkspaceTask(workspace, task!.id));
    function validateChanges(changes: PreparedCalculatorChanges): PreparedCalculatorChanges {
      // Rebuild static/policy/secret gates before storing a successful proposal.
      const raw = JSON.parse(changes.reviewEvidence);
      const verified = prepareCalculatorRoleChanges(task!.role, { summary: changes.summary,
        changes: raw.changes.map((change: Record<string, unknown>) => {
          const message = changes.files.find(file => file.path === change.path)?.message;
          return change.operation === "create" ? { operation: "create", path: change.path, content: change.content, message } :
            { operation: change.operation, path: change.path, sourceSha256: change.sourceSha256, edits: change.edits, message };
        }) }, snapshot);
      if (calculatorProposalDigest(verified) !== calculatorProposalDigest(changes) || verified.reviewEvidence !== changes.reviewEvidence ||
          changes.repository !== workspace.repository || changes.baseSha !== workspace.sha || changes.baseRef !== workspace.ref ||
          !changes.files.length || changes.files.some(file => !task!.paths.includes(file.path)) ||
          task!.paths.some(path => !changes.files.some(file => file.path === path) && !snapshot.files.some(file => file.path === path && file.exists)))
        return refuseCalculatorExecution();
      return changes;
    }
    let changes = await stage(options.rejectedProposalPermit?'repair_2':options.restoreProposal ? "restore_proposal_1" : "generate_1", async () => {
      await assertCalculatorWorkspaceCurrent(workspace); attempts++;
      const result = options.restoreProposal ? await options.restoreProposal(plan, task!.id, snapshot) : await options.team.generate(plan, task!.id, snapshot);
      await assertCalculatorWorkspaceCurrent(workspace);
      checkpointProposal = validateChanges(result); return checkpointProposal;
    });
    const restored: readonly CalculatorAssessment[] = options.restoreAssessments ? await options.restoreAssessments(plan, task.id, changes) : [];
    if (options.restoreAssessments && (!Array.isArray(restored) || restored.length !== 2 ||
        restored.some((value, index) => value.role !== (["security", "reviewer"] as const)[index]))) return refuseCalculatorExecution();
    for (let attempt = activeAttempt; attempt <= 2; attempt++) {
      const issues: string[] = [];
      for (const role of ["security", "reviewer", "tester"] as const) {
        const prior: CalculatorAssessment | undefined = restored.find(value => value.role === role);
        const assessment = await stage((prior ? "restore_" : "") + role + "_" + attempt, async () => {
          await assertCalculatorWorkspaceCurrent(workspace);
          const value = prior ?? await options.team.assess(role, plan, task!.id, changes);
          await assertCalculatorWorkspaceCurrent(workspace);
          if (value.role !== role || typeof value.ready !== "boolean" || value.testsExecuted !== false ||
              value.publicationAuthorized !== false || value.overallTaskCompletionVerified !== false) return refuseCalculatorExecution();
          assessments.push(value); return value;
        });
        if (!assessment.ready || assessment.findings.some(finding => finding.severity === "blocker" || finding.severity === "high"))
          issues.push(role + ": " + assessment.summary);
      }
      let checks: CalculatorProposalTests | undefined;
      if (!issues.length) checks = await stage("host_tests_" + attempt, async () => {
        await assertCalculatorWorkspaceCurrent(workspace);
        const result = validateCalculatorProposalTests(await options.tools.checkProposal({ task: task!, changes,
          proposalDigest: calculatorProposalDigest(changes) }), task!.id, changes);
        await assertCalculatorWorkspaceCurrent(workspace); return result;
      });
      proposalTestsExecuted = checks?.testsExecuted === true;
      if (checks?.status === "unverified") return await finish("blocked", "proposal_tests_unverified");
      if (checks?.status === "failed") issues.push(...checks.failures);
      if (issues.length) {
        // Failure is persisted before any repair call. A crash never resets attempts.
        const failed = "checks_failed_" + attempt;
        activeStage = failed; receipt.recordStage(failed, "running");
        await checkpoint(failed, "blocked"); receipt.recordStage(failed, "blocked"); activeStage = undefined;
        if (repairs >= maxRepairs) return await finish("blocked", "repair_limit_reached");
        activeAttempt = 2; attempts++; repairs++;
        changes = await stage("repair_2", async () => {
          await assertCalculatorWorkspaceCurrent(workspace);
          const request = options.team.prepareRepairFeedback ?
            options.team.prepareRepairFeedback(plan, task!.id, changes, checks) : {
              previous: changes, proposalDigest: calculatorProposalDigest(changes), issues: Object.freeze([...issues]),
            };
          const result = await options.team.repair(plan, task!.id, snapshot, request);
          await assertCalculatorWorkspaceCurrent(workspace);
          checkpointProposal = validateChanges(result); assessments = []; return checkpointProposal;
        });
        continue;
      }
      if (!checks || checks.status !== "passed" || !checks.testsExecuted) return await finish("blocked", "proposal_tests_unverified");
      publication = await stage("publish_candidate", async () => {
        await assertCalculatorWorkspaceCurrent(workspace); publicationStarted = true;
        await checkpoint("publish_candidate", "running");
        const candidate = await options.tools.publish({ task: task!, changes, expectedSha: workspace.sha, branch: plan.branch });
        if (candidate.branch !== plan.branch || !/^[a-f0-9]{40}$/.test(candidate.headSha) ||
            !Number.isSafeInteger(candidate.number) || candidate.number < 1 ||
            candidate.url !== "https://github.com/" + workspace.repository + "/pull/" + candidate.number) return refuseCalculatorExecution();
        receipt!.recordPublication(candidate); publication = { ...candidate };
        await assertCalculatorPublishedCandidate(workspace, candidate.headSha, changes); return candidate;
      });
      const ci = await stage("verify_candidate_ci", async () => {
        const result = await options.tools.ci({ repository: workspace.repository, branch: plan.branch, candidateSha: publication!.headSha });
        if (result.repository !== workspace.repository || result.branch !== plan.branch || result.candidateSha !== publication!.headSha ||
            result.runs.some(run => run.html_url !== "https://github.com/" + workspace.repository + "/actions/runs/" + run.id)) return refuseCalculatorExecution();
        await assertCalculatorPublishedCandidate(workspace, publication!.headSha, changes);
        return evaluateTestExecutionEvidence(result.runs, result.jobs, publication!.headSha, ["Calculator task CI"], ["Syntax", "Task tests"]);
      });
      candidateTestsExecuted = ci.testsExecuted;
      if (ci.status === "failed") return await finish("blocked", "candidate_ci_failed_explicit_repair_required");
      if (!ci.testsExecuted) return await finish("needs-review", "candidate_ci_pending_no_polling");
      return await finish("needs-review", "task_candidate_verified_not_whole_app", "candidate-verified");
    }
    return await finish("blocked", "repair_limit_reached");
  } catch (error) {
    publicationDiagnostic=calculatorPublicationDiagnostic(error);
    if (!receipt) return answer("blocked", "workspace_or_configuration_unverified");
    const candidateUnverified = publication !== undefined && activeStage === "publish_candidate";
    // A failed write is itself terminal: preserve the previous private evidence
    // and still close the source-free replay barrier. No model/tool follows it.
    try { await checkpoint(activeStage ?? "execution_failed", "blocked"); } catch { /* Previous capsule remains authoritative. */ }
    if (activeStage) { receipt.recordStage(activeStage, "blocked"); activeStage = undefined; }
    if (candidateUnverified) return await finish("blocked", "published_candidate_unverified_no_replay", "blocked", false);
    return await finish(publicationStarted ? "needs-review" : "blocked",
      publicationStarted ? "publication_or_ci_uncertain_inspect_no_replay" : "execution_failed_no_replay",
      publicationStarted ? "needs-review" : "blocked", false);
  } finally { receipt?.close(); }
}
