import { TezJetRepositoryAdapter } from "./tezjetRepository.js";

const PROTECTED = new Set(["main", "master"]);

export async function prepareTezJetChange(input: {
  branch: string;
  title: string;
  body: string;
  files: Array<{ path: string; content: string; message: string }>;
}) {
  if (!input.branch || PROTECTED.has(input.branch)) throw new Error("A non-protected feature branch is required.");
  if (!input.files.length) throw new Error("Cannot create a change without files.");
  if (input.files.some((file) => !file.path || !file.content || !file.message)) {
    throw new Error("Every change file must include path, content, and commit message.");
  }

  const repository = process.env.TEZJET_REPOSITORY ?? "erman-ksv/TezJet";
  const adapter = new TezJetRepositoryAdapter(repository);
  await adapter.prepareBranch(input.branch, "main");

  for (const file of input.files) {
    await adapter.write(file.path, file.content, file.message, input.branch);
  }

  return adapter.openDraftPullRequest(
    input.branch,
    input.title,
    input.body + "\n\nGenerated by TezJet-Agent-Factory. Changes are gated by review and security checks.",
  );
}
