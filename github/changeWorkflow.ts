import { TezJetRepositoryAdapter } from "./tezjetRepository.js";
import { getTargetRepository } from "./repositoryConfig.js";
import { assertCommitSha, assertValidBranchRef } from "./githubClient.js";

const PROTECTED = new Set(["main", "master"]);

export async function prepareTezJetChange(input: {
  branch: string;
  title: string;
  body: string;
  files: Array<{ path: string; content: string; message: string }>;
  repository?: string;
  baseRef?: string;
  baseSha?: string;
}) {
  if (!input.branch || PROTECTED.has(input.branch)) throw new Error("A non-protected feature branch is required.");
  const baseRef = input.baseRef ?? "main";
  assertValidBranchRef(input.branch);
  assertValidBranchRef(baseRef);
  if (input.branch === baseRef) throw new Error("The feature branch must differ from the pull request base.");
  if (input.baseSha !== undefined) assertCommitSha(input.baseSha);
  if (!input.files.length) throw new Error("Cannot create a change without files.");
  if (input.files.some((file) => !file.path || !file.content || !file.message)) {
    throw new Error("Every change file must include path, content, and commit message.");
  }

  const repository = input.repository ?? getTargetRepository();
  const adapter = new TezJetRepositoryAdapter(repository);
  await adapter.prepareBranch(input.branch, baseRef, input.baseSha);

  let headSha = "";
  for (const file of input.files) {
    headSha = await adapter.write(file.path, file.content, file.message, input.branch);
  }

  const pullRequest = await adapter.openDraftPullRequest(
    input.branch,
    input.title,
    input.body + "\n\nGenerated by TezJet-Agent-Factory. Changes are gated by review and security checks.",
    baseRef,
  );
  if (!headSha || pullRequest.head.sha.toLowerCase() !== headSha.toLowerCase()) {
    throw new Error("The draft pull request head does not match the published candidate commit SHA.");
  }
  return { ...pullRequest, head_sha: headSha };
}

